import { hashPassword as hashBetterAuthPassword } from "better-auth/crypto";

declare const betterAuthPasswordHashBrand: unique symbol;

export type BetterAuthPasswordHash = string & {
  readonly [betterAuthPasswordHashBrand]: true;
};

// Better Auth 1.7.6 creates a 16-byte hex salt and a 64-byte scrypt key.
const BETTER_AUTH_PASSWORD_HASH_PATTERN = /^[a-f0-9]{32}:[a-f0-9]{128}$/;

export function isBetterAuthPasswordHash(value: unknown): value is BetterAuthPasswordHash {
  return typeof value === "string" && BETTER_AUTH_PASSWORD_HASH_PATTERN.test(value);
}

export function parseBetterAuthPasswordHash(value: unknown): BetterAuthPasswordHash {
  if (!isBetterAuthPasswordHash(value)) {
    throw new Error("Password hash must use the format generated by Better Auth.");
  }
  return value;
}

export async function hashApplicationPassword(password: string): Promise<BetterAuthPasswordHash> {
  return parseBetterAuthPasswordHash(await hashBetterAuthPassword(password));
}
