import { describe, expect, it } from "vitest";
import {
  hashApplicationPassword,
  isBetterAuthPasswordHash,
  parseBetterAuthPasswordHash,
} from "../../src/lib/auth/password-hash";

describe("Better Auth password hash contract", () => {
  it("accepts hashes produced by the application Better Auth flow", async () => {
    const hash = await hashApplicationPassword("synthetic-wave-six-password");
    expect(isBetterAuthPasswordHash(hash)).toBe(true);
    expect(parseBetterAuthPasswordHash(hash)).toBe(hash);
  });

  it("rejects placeholder prefixes and arbitrary strings", () => {
    for (const value of [
      "$argon2id$synthetic-test-hash-only",
      "different-retry-hash-ignored",
      "0123456789abcdef0123456789abcdef:short",
      "0123456789abcdef0123456789abcdef:" + "g".repeat(128),
      "",
    ]) {
      expect(isBetterAuthPasswordHash(value)).toBe(false);
      expect(() => parseBetterAuthPasswordHash(value)).toThrow("format generated by Better Auth");
    }
  });
});
